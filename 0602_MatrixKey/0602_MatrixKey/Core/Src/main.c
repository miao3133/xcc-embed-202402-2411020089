#include "main.h"

void SystemClock_Config(void);
static void MX_GPIO_Init(void);

uint8_t PreLine[4] = {3,2,0,1};
uint16_t KeyVal = 0;

int main(void)
{
  HAL_Init();
  SystemClock_Config();
  MX_GPIO_Init();

  while (1)
  {
    uint8_t i;
    KeyVal = 0;
    for(i = 0; i < 4; i++)
    {
      GPIOE->ODR = ~(1U << i);
      HAL_Delay(16);

      switch( GPIOE->IDR & 0x00F0U )
      {
        case 0x00E0U: KeyVal = 4 * PreLine[i] + 1; break;
        case 0x00D0U: KeyVal = 4 * PreLine[i] + 2; break;
        case 0x00B0U: KeyVal = 4 * PreLine[i] + 3; break;
        case 0x0070U: KeyVal = 4 * PreLine[i] + 4; break;
        default: KeyVal = 0; break;
      }

      if(KeyVal != 0)
      {
        while( (GPIOE->IDR & 0x00F0U) != 0x00F0U );
        HAL_GPIO_TogglePin(GPIOF, GPIO_PIN_7);
        break;
      }
    }
  }
}

